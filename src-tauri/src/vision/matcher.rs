impl DigitMatcher {
    /// Choose cuts across an outlined/touching number using whole-digit evidence.
    /// Low column counts supply candidate cuts; dynamic programming discourages
    /// explaining one rounded digit as two narrow fragments.
    pub(crate) fn split_number_component(
        comp: &DetectedComponent,
    ) -> Option<Vec<DetectedComponent>> {
        use std::sync::OnceLock;
        static TEMPLATES: OnceLock<DigitTemplates> = OnceLock::new();
        let templates = TEMPLATES.get_or_init(DigitTemplates::new);
        let w = comp.bbox.width as usize;
        let h = comp.bbox.height as usize;
        let mut columns = vec![0usize; w];
        for row in comp.mask.chunks_exact(w) {
            for (x, &p) in row.iter().enumerate() {
                columns[x] += usize::from(p > 0);
            }
        }
        let min_w = (h as f32 * 0.18).ceil() as usize;
        let mut cuts = vec![0];
        let mut x = min_w.max(1);
        while x + min_w < w {
            let start = x;
            while x + 1 < w && columns[x + 1] == columns[start] {
                x += 1;
            }
            if columns[start] <= (h as f32 * 0.65) as usize
                && columns[start] <= columns[start - 1]
                && x + 1 < w
                && columns[x] <= columns[x + 1]
            {
                cuts.push((start + x) / 2);
            }
            x += 1;
        }
        cuts.push(w);
        // Bound noisy scenery work; ordinary damage numbers need far fewer cuts.
        if cuts.len() > 32 {
            return None;
        }
        let mut costs = vec![f32::INFINITY; cuts.len()];
        let mut paths: Vec<Option<(usize, DetectedComponent)>> = vec![None; cuts.len()];
        costs[0] = 0.0;
        for end in 1..cuts.len() {
            for start in 0..end {
                let left = cuts[start];
                let right = cuts[end];
                if !costs[start].is_finite() || right - left < min_w || right - left > h {
                    continue;
                }
                let mut x0 = right;
                let mut x1 = left;
                let mut y0 = h;
                let mut y1 = 0;
                for y in 0..h {
                    for x in left..right {
                        if comp.mask[y * w + x] > 0 {
                            x0 = x0.min(x);
                            x1 = x1.max(x);
                            y0 = y0.min(y);
                            y1 = y1.max(y);
                        }
                    }
                }
                if x0 > x1 || y0 > y1 {
                    continue;
                }
                let cw = x1 - x0 + 1;
                let ch = y1 - y0 + 1;
                if ch < h * 3 / 4 {
                    continue;
                }
                let mut mask = Vec::with_capacity(cw * ch);
                for y in y0..=y1 {
                    mask.extend_from_slice(&comp.mask[y * w + x0..y * w + x1 + 1]);
                }
                let (_, score) = templates.match_glyph(&mask, cw, ch);
                if score < 0.50 {
                    continue;
                }
                let cost = costs[start] + 1.0 - score.clamp(0.0, 1.0) + 0.30;
                if cost < costs[end] {
                    costs[end] = cost;
                    paths[end] = Some((
                        start,
                        DetectedComponent {
                            bbox: crate::vision::filter::BoundingBox {
                                x: comp.bbox.x + x0 as u32,
                                y: comp.bbox.y + y0 as u32,
                                width: cw as u32,
                                height: ch as u32,
                            },
                            element: comp.element,
                            hue: comp.hue,
                            pixel_count: mask.iter().filter(|&&p| p > 0).count(),
                            mask,
                        },
                    ));
                }
            }
        }
        let mut end = cuts.len() - 1;
        let mut glyphs = Vec::new();
        while end > 0 {
            let (start, glyph) = paths[end].take()?;
            glyphs.push(glyph);
            end = start;
        }
        glyphs.reverse();
        (glyphs.len() >= 2).then_some(glyphs)
    }

    pub fn new() -> Self {
        Self {
            templates: DigitTemplates::new(),
        }
    }

    /// Recover a digit split at a thin stroke by the projection stage. Merge only
    /// adjacent fragments when the combined shape scores better than either part.
    fn merge_fragments(&self, glyphs: &[DetectedComponent]) -> Vec<DetectedComponent> {
        let mut result = Vec::new();
        let mut i = 0;
        while i < glyphs.len() {
            let a = &glyphs[i];
            if let Some(b) = glyphs.get(i + 1) {
                let bbox = a.bbox.merge(&b.bbox);
                let gap = b.bbox.x as i64 - i64::from(a.bbox.x + a.bbox.width);
                if (-1..=1).contains(&gap) && bbox.width as f32 / bbox.height as f32 <= 0.98 {
                    let mut merged = DetectedComponent {
                        bbox,
                        element: a.element,
                        hue: a.hue,
                        pixel_count: 0,
                        mask: vec![0; (bbox.width * bbox.height) as usize],
                    };
                    for g in [a, b] {
                        for y in 0..g.bbox.height {
                            for x in 0..g.bbox.width {
                                let value = g.mask[(y * g.bbox.width + x) as usize];
                                let index = ((g.bbox.y - bbox.y + y) * bbox.width + g.bbox.x
                                    - bbox.x
                                    + x) as usize;
                                merged.mask[index] |= value;
                            }
                        }
                    }
                    merged.pixel_count = merged.mask.iter().filter(|&&p| p > 0).count();
                    let (_, combined) = self.templates.match_glyph(
                        &merged.mask,
                        bbox.width as usize,
                        bbox.height as usize,
                    );
                    let (_, sa) = self.templates.match_glyph(
                        &a.mask,
                        a.bbox.width as usize,
                        a.bbox.height as usize,
                    );
                    let (_, sb) = self.templates.match_glyph(
                        &b.mask,
                        b.bbox.width as usize,
                        b.bbox.height as usize,
                    );
                    if combined >= 0.60 && combined > sa.max(sb) + 0.08 {
                        result.push(merged);
                        i += 2;
                        continue;
                    }
                }
            }
            result.push(a.clone());
            i += 1;
        }
        result
    }

    /// Split two touching glyphs using column projection valley search
    pub fn split_touching_glyphs(
        &self,
        mask: &[u8],
        w: usize,
        h: usize,
    ) -> Vec<(Vec<u8>, usize, usize)> {
        if w == 0 || h == 0 || w.checked_mul(h).is_none_or(|len| mask.len() < len) {
            return Vec::new();
        }
        let mut col_proj = vec![0usize; w];
        for x in 0..w {
            for y in 0..h {
                if mask[y * w + x] > 0 {
                    col_proj[x] += 1;
                }
            }
        }

        // Search for a valley in middle 35%..65% of width
        let min_search_x = (w as f32 * 0.35) as usize;
        let max_search_x = (w as f32 * 0.65) as usize;

        let mut min_val = usize::MAX;
        let mut split_x = 0;

        for x in min_search_x..=max_search_x {
            if col_proj[x] < min_val {
                min_val = col_proj[x];
                split_x = x;
            }
        }

        // If valley is pronounced (less than 40% of max height), split
        if split_x > 0 && min_val < (h as f32 * 0.45) as usize {
            let w1 = split_x;
            let w2 = w - split_x;

            let mut crop1 = vec![0u8; w1 * h];
            for y in 0..h {
                for x in 0..w1 {
                    crop1[y * w1 + x] = mask[y * w + x];
                }
            }

            let mut crop2 = vec![0u8; w2 * h];
            for y in 0..h {
                for x in 0..w2 {
                    crop2[y * w2 + x] = mask[y * w + (split_x + x)];
                }
            }

            return vec![(crop1, w1, h), (crop2, w2, h)];
        }

        vec![(mask.to_vec(), w, h)]
    }

    /// Recognize an assembled horizontal damage cluster into a damage number
    pub fn recognize_cluster(&self, cluster: &DamageCluster, scale: f32) -> Option<RecognizedHit> {
        let merged = DamageCluster {
            glyphs: self.merge_fragments(&cluster.glyphs),
            ..cluster.clone()
        };
        let cluster = &merged;
        if cluster.glyphs.is_empty() {
            return None;
        }

        // Damage numbers in Genshin Impact (720p to 4K) are at least 14*scale px tall.
        // Rejects thin foliage/speckles.
        let min_cluster_h = (14.0 * scale) as u32;
        if cluster.bbox.height < min_cluster_h {
            return None;
        }

        let mut recognized_digits = Vec::new();
        let mut total_conf = 0.0f32;
        let mut has_crit_mark = false;
        let mut exclamation_count = 0;

        // Calculate cluster baseline and cap-height to clamp hanging spark/weapon artifacts
        let mut bottoms: Vec<u32> = cluster
            .glyphs
            .iter()
            .map(|g| g.bbox.y + g.bbox.height)
            .collect();
        bottoms.sort_unstable();
        let median_bottom = bottoms[bottoms.len() / 2];

        let mut tops: Vec<u32> = cluster.glyphs.iter().map(|g| g.bbox.y).collect();
        tops.sort_unstable();
        let median_top = tops[tops.len() / 2];

        let clamp_margin = (1.0 * scale).round() as u32;
        let max_allowed_bottom = median_bottom + clamp_margin;
        let min_allowed_top = median_top.saturating_sub(clamp_margin);

        for g in &cluster.glyphs {
            let g_top = g.bbox.y;
            let g_bot = g.bbox.y + g.bbox.height;
            let (crop_mask, gw, gh) = if (g_bot > max_allowed_bottom || g_top < min_allowed_top)
                && cluster.glyphs.len() >= 3
            {
                let valid_top = g_top.max(min_allowed_top);
                let valid_bot = g_bot.min(max_allowed_bottom);
                if valid_bot <= valid_top || valid_top < g_top || valid_bot < g_top {
                    (
                        g.mask.clone(),
                        g.bbox.width as usize,
                        g.bbox.height as usize,
                    )
                } else {
                    let rel_top = (valid_top - g_top) as usize;
                    let rel_bot = (valid_bot - g_top) as usize;

                    let mut min_x = usize::MAX;
                    let mut max_x = 0;
                    let orig_w = g.bbox.width as usize;

                    for y in rel_top..rel_bot {
                        for x in 0..orig_w {
                            if g.mask[y * orig_w + x] > 0 {
                                min_x = min_x.min(x);
                                max_x = max_x.max(x);
                            }
                        }
                    }

                    if min_x <= max_x && rel_bot > rel_top {
                        let tw = max_x - min_x + 1;
                        let th = rel_bot - rel_top;
                        let mut tight = vec![0u8; tw * th];
                        for y in 0..th {
                            for x in 0..tw {
                                tight[y * tw + x] = g.mask[(rel_top + y) * orig_w + (min_x + x)];
                            }
                        }
                        (tight, tw, th)
                    } else {
                        (
                            g.mask.clone(),
                            g.bbox.width as usize,
                            g.bbox.height as usize,
                        )
                    }
                }
            } else {
                (
                    g.mask.clone(),
                    g.bbox.width as usize,
                    g.bbox.height as usize,
                )
            };

            // Check for critical exclamation mark: narrow, tall with gap before bottom dot
            let aspect = gw as f32 / gh as f32;
            let min_excl_h = (20.0 * scale) as usize;
            if aspect <= 0.40 && gh >= min_excl_h {
                let bottom_start = (gh as f32 * 0.65) as usize;
                let bottom_end = (gh as f32 * 0.85) as usize;
                let mut has_gap = false;
                for y in bottom_start..bottom_end {
                    let mut row_count = 0;
                    for x in 0..gw {
                        if crop_mask[y * gw + x] > 0 {
                            row_count += 1;
                        }
                    }
                    if row_count == 0 {
                        has_gap = true;
                        break;
                    }
                }
                if has_gap {
                    has_crit_mark = true;
                    exclamation_count += 1;
                    continue; // Skip exclamation mark from numerical digits
                }
            }

            // Touching glyphs split
            let min_touch_w = (18.0 * scale) as usize;
            if aspect >= 1.15 && gw >= min_touch_w {
                let sub_glyphs = self.split_touching_glyphs(&crop_mask, gw, gh);
                if sub_glyphs.len() >= 2 {
                    for (crop, cw, ch) in sub_glyphs {
                        let sub_asp = cw as f32 / ch as f32;
                        if sub_asp < 0.18 || sub_asp > 0.98 {
                            return None;
                        }
                        let (digit, conf) = self.templates.match_glyph(&crop, cw, ch);
                        if conf >= 0.50 {
                            recognized_digits.push(digit);
                            total_conf += conf;
                        } else {
                            return None;
                        }
                    }
                    continue;
                }
            }

            // An unsplit single digit in Genshin never exceeds aspect 0.98
            if aspect > 0.98 {
                return None;
            }

            let (digit, conf) = self.templates.match_glyph(&crop_mask, gw, gh);
            if conf >= 0.50 {
                recognized_digits.push(digit);
                total_conf += conf;
            } else {
                return None;
            }
        }

        // In a real damage number, all non-crit glyphs must be recognized as digits
        let expected_digits = cluster.glyphs.len().saturating_sub(exclamation_count);
        if recognized_digits.len() < expected_digits || recognized_digits.len() < 2 {
            return None;
        }

        let avg_conf = total_conf / recognized_digits.len() as f32;
        if avg_conf < 0.67 {
            return None;
        }

        // For short 2-digit numbers, require higher confidence (>= 0.70) to filter background noise (e.g. 10, 12, 21)
        if recognized_digits.len() <= 2 && avg_conf < 0.70 {
            return None;
        }

        // Environmental artifact rejection: candidate numbers composed largely of 1s (e.g. >= 50%)
        // from vertical environmental features (tree trunks, pillars, fences, rock fissures).
        // Real damage numbers dominated by 1s are rare and will have high template confidence (>= 0.78).
        let ones_count = recognized_digits.iter().filter(|&&d| d == 1).count();
        let ones_ratio = ones_count as f32 / recognized_digits.len() as f32;
        if ones_ratio >= 0.50 && avg_conf < 0.78 {
            return None;
        }

        let mut value = 0u32;
        for d in recognized_digits.iter() {
            value = value.saturating_mul(10).saturating_add(*d);
        }

        // Damage bounds: realistic range in Genshin Impact
        if value < 10 || value > 99_999_999 {
            return None;
        }

        let crit_height_threshold = (27.0 * scale) as u32;
        let is_crit =
            has_crit_mark || cluster.is_crit || cluster.bbox.height >= crit_height_threshold;

        Some(RecognizedHit {
            value,
            is_crit,
            confidence: avg_conf,
            x: cluster.bbox.x as i32 + (cluster.bbox.width as i32 / 2),
            y: cluster.bbox.y as i32,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{state::ElementType, vision::filter::BoundingBox};

    fn glyph(digit: usize, x: u32) -> DetectedComponent {
        let mask = DigitTemplates::new().templates[digit].to_vec();
        DetectedComponent {
            bbox: BoundingBox {
                x,
                y: 100,
                width: 16,
                height: 24,
            },
            element: ElementType::Pyro,
            hue: 35,
            pixel_count: mask.iter().filter(|&&p| p > 0).count(),
            mask,
        }
    }

    #[test]
    fn rejects_incomplete_buffers_without_panicking() {
        let matcher = DigitMatcher::new();
        assert_eq!(matcher.templates.match_glyph(&[255], 16, 24), (0, 0.0));
        assert!(matcher.split_touching_glyphs(&[255], 32, 24).is_empty());
        assert!(matcher
            .split_touching_glyphs(&[], usize::MAX, 24)
            .is_empty());
    }

    #[test]
    fn critical_flag_cannot_hide_an_unrecognized_digit() {
        let matcher = DigitMatcher::new();
        let a = glyph(2, 0);
        let b = glyph(6, 20);
        let mut c = glyph(3, 40);
        c.mask.fill(0);
        let cluster = DamageCluster {
            element: ElementType::Pyro,
            bbox: a.bbox.merge(&c.bbox),
            glyphs: vec![a, b, c],
            is_crit: true,
        };
        assert!(matcher.recognize_cluster(&cluster, 1.0).is_none());
    }

    #[test]
    fn rejoins_fragments_without_merging_adjacent_complete_digits() {
        let matcher = DigitMatcher::new();
        let full = glyph(0, 0);
        let mut a = full.clone();
        let mut b = full.clone();
        a.bbox.width = 8;
        b.bbox.x = 8;
        b.bbox.width = 8;
        a.mask = full
            .mask
            .chunks(16)
            .flat_map(|row| row[..8].iter().copied())
            .collect();
        b.mask = full
            .mask
            .chunks(16)
            .flat_map(|row| row[8..].iter().copied())
            .collect();
        let joined = matcher.merge_fragments(&[a, b]);
        assert_eq!(joined.len(), 1);
        assert_eq!(joined[0].mask, full.mask);
        assert_eq!(
            matcher.merge_fragments(&[glyph(2, 0), glyph(6, 17)]).len(),
            2
        );
    }

    #[test]
    fn test_template_self_match() {
        let matcher = DigitMatcher::new();
        for digit in 0..10 {
            let t = &matcher.templates.templates[digit];
            if digit == 1 {
                let mut narrow = [0u8; 8 * 24];
                for y in 0..24 {
                    for x in 0..8 {
                        narrow[y * 8 + x] = t[y * 16 + (8 + x)];
                    }
                }
                let (matched, score) = matcher.templates.match_glyph(&narrow, 8, 24);
                assert_eq!(matched, 1, "Self match failed for digit 1");
                assert!(
                    score >= 0.70,
                    "Self match score {} too low for digit 1",
                    score
                );
            } else {
                let (matched, score) = matcher.templates.match_glyph(t, TEMPLATE_W, TEMPLATE_H);
                assert_eq!(
                    matched, digit as u32,
                    "Self match failed for digit {}",
                    digit
                );
                assert!(
                    score >= 0.80,
                    "Self match score {} too low for digit {}",
                    score,
                    digit
                );
            }
        }
    }
}
