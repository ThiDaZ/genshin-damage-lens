pub struct DigitTemplates {
    pub templates: [[u8; 384]; 10],
    pub alt_templates: [Vec<[u8; 384]>; 10],
}

impl DigitTemplates {
    pub fn new() -> Self {
        let mut alt_templates: [Vec<[u8; 384]>; 10] = Default::default();
        alt_templates[0].push(DIGIT_0_CRIT);
        alt_templates[1].push(DIGIT_1_CRIT);
        alt_templates[2].push(DIGIT_2_CRIT);
        alt_templates[3].push(DIGIT_3_CRIT);
        alt_templates[4].push(DIGIT_4_CRIT);
        alt_templates[4].push(DIGIT_4_LOW_BAR);
        alt_templates[5].push(DIGIT_5_CRIT);
        alt_templates[6].push(DIGIT_6_CRIT);
        alt_templates[8].push(DIGIT_8_CRIT);
        alt_templates[9].push(DIGIT_9_CRIT);
        alt_templates[9].push(DIGIT_9_CRIT_SLANTED);

        Self {
            templates: [
                DIGIT_0, DIGIT_1, DIGIT_2, DIGIT_3, DIGIT_4,
                DIGIT_5, DIGIT_6, DIGIT_7, DIGIT_8, DIGIT_9,
            ],
            alt_templates,
        }
    }

    /// Match an arbitrary binary image crop against templates
    pub fn match_glyph(&self, crop: &[u8], cw: usize, ch: usize) -> (u32, f32) {
        if cw == 0 || ch == 0 || crop.is_empty() {
            return (0, 0.0);
        }

        let aspect = cw as f32 / ch as f32;
        // Individual digits in Genshin never exceed aspect 0.98 or have aspect < 0.18
        if aspect < 0.18 || aspect > 0.98 {
            return (0, 0.0);
        }

        // Resample crop to 16x24
        let mut normalized = [0u8; TEMPLATE_W * TEMPLATE_H];
        for ty in 0..TEMPLATE_H {
            let sy = (ty * ch) / TEMPLATE_H;
            for tx in 0..TEMPLATE_W {
                let sx = (tx * cw) / TEMPLATE_W;
                normalized[ty * TEMPLATE_W + tx] = if crop[sy * cw + sx] > 0 { 1 } else { 0 };
            }
        }

        let mut best_digit = 0;
        let mut best_score = -1.0f32;

        for (digit, t) in self.templates.iter().enumerate() {
            let mut score = Self::calc_iou(&normalized, t);

            for alt in &self.alt_templates[digit] {
                let alt_score = Self::calc_iou(&normalized, alt);
                score = score.max(alt_score);
            }

            let raw_score = score;

            if digit == 1 {
                // Digit 1 in Genshin is narrow (aspect 0.22 to 0.48)
                if aspect <= 0.48 && raw_score >= 0.28 {
                    score += 0.20;
                } else if aspect >= 0.52 {
                    score -= 0.35;
                }
            } else if digit == 8 {
                // Digit 8 must have inner holes / voids (upper loop and lower loop)
                // In a solid blob or cloud, both hole areas are solid 1s
                let mut upper_hole_ones = 0;
                for ty in 5..8 {
                    for tx in 7..10 {
                        if normalized[ty * TEMPLATE_W + tx] == 1 {
                            upper_hole_ones += 1;
                        }
                    }
                }
                let mut lower_hole_ones = 0;
                for ty in 17..21 {
                    for tx in 7..10 {
                        if normalized[ty * TEMPLATE_W + tx] == 1 {
                            lower_hole_ones += 1;
                        }
                    }
                }
                // Upper hole has 9 pixels, lower hole has 16 pixels
                if upper_hole_ones >= 6 || lower_hole_ones >= 10 {
                    score -= 0.40;
                }
                if aspect <= 0.38 {
                    score -= 0.30;
                }
            } else {
                if aspect <= 0.38 {
                    score -= 0.30;
                }
            }

            if score > best_score {
                best_score = score;
                best_digit = digit as u32;
            }
        }

        (best_digit, best_score)
    }

    fn calc_iou(norm: &[u8; 384], t: &[u8; 384]) -> f32 {
        let mut match_count = 0usize;
        let mut total_count = 0usize;

        for i in 0..norm.len() {
            let p1 = norm[i] == 1;
            let p2 = t[i] == 1;
            if p1 || p2 {
                total_count += 1;
                if p1 == p2 {
                    match_count += 1;
                }
            }
        }

        if total_count > 0 {
            match_count as f32 / total_count as f32
        } else {
            0.0
        }
    }
}

pub struct DigitMatcher {
    pub templates: DigitTemplates,
}

impl DigitMatcher {
    pub fn new() -> Self {
        Self {
            templates: DigitTemplates::new(),
        }
    }

    /// Split two touching glyphs using column projection valley search
    pub fn split_touching_glyphs(&self, mask: &[u8], w: usize, h: usize) -> Vec<(Vec<u8>, usize, usize)> {
        let mut col_proj = vec![0usize; w];
        for x in 0..w {
            for y in 0..h {
                if mask[y * w + x] > 0 {
                    col_proj[x] += 1;
                }
            }
        }

        // Search for a valley in middle 35%..65% of width
        let min_search_x = (w as f32 * 0.35) as usize;
        let max_search_x = (w as f32 * 0.65) as usize;

        let mut min_val = usize::MAX;
        let mut split_x = 0;

        for x in min_search_x..=max_search_x {
            if col_proj[x] < min_val {
                min_val = col_proj[x];
                split_x = x;
            }
        }

        // If valley is pronounced (less than 40% of max height), split
        if split_x > 0 && min_val < (h as f32 * 0.45) as usize {
            let w1 = split_x;
            let w2 = w - split_x;

            let mut crop1 = vec![0u8; w1 * h];
            for y in 0..h {
                for x in 0..w1 {
                    crop1[y * w1 + x] = mask[y * w + x];
                }
            }

            let mut crop2 = vec![0u8; w2 * h];
            for y in 0..h {
                for x in 0..w2 {
                    crop2[y * w2 + x] = mask[y * w + (split_x + x)];
                }
            }

            return vec![(crop1, w1, h), (crop2, w2, h)];
        }

        vec![(mask.to_vec(), w, h)]
    }

    /// Recognize an assembled horizontal damage cluster into a damage number
    pub fn recognize_cluster(&self, cluster: &DamageCluster) -> Option<RecognizedHit> {
        if cluster.glyphs.is_empty() {
            return None;
        }

        // Damage numbers in Genshin Impact (720p to 4K) are at least 15px tall.
        // Rejects thin foliage/speckles.
        if cluster.bbox.height < 15 {
            return None;
        }

        let mut recognized_digits = Vec::new();
        let mut total_conf = 0.0f32;
        let mut has_crit_mark = cluster.is_crit;

        // Calculate cluster baseline and cap-height to clamp hanging spark/weapon artifacts
        let mut bottoms: Vec<u32> = cluster.glyphs.iter().map(|g| g.bbox.y + g.bbox.height).collect();
        bottoms.sort_unstable();
        let median_bottom = bottoms[bottoms.len() / 2];

        let mut tops: Vec<u32> = cluster.glyphs.iter().map(|g| g.bbox.y).collect();
        tops.sort_unstable();
        let median_top = tops[tops.len() / 2];

        let max_allowed_bottom = median_bottom + 1;
        let min_allowed_top = median_top.saturating_sub(1);

        for g in &cluster.glyphs {
            let g_top = g.bbox.y;
            let g_bot = g.bbox.y + g.bbox.height;
            let (crop_mask, gw, gh) = if (g_bot > max_allowed_bottom || g_top < min_allowed_top) && cluster.glyphs.len() >= 3 {
                let valid_top = g_top.max(min_allowed_top);
                let valid_bot = g_bot.min(max_allowed_bottom);
                let rel_top = (valid_top - g_top) as usize;
                let rel_bot = (valid_bot - g_top) as usize;

                let mut min_x = usize::MAX;
                let mut max_x = 0;
                let orig_w = g.bbox.width as usize;

                for y in rel_top..rel_bot {
                    for x in 0..orig_w {
                        if g.mask[y * orig_w + x] > 0 {
                            min_x = min_x.min(x);
                            max_x = max_x.max(x);
                        }
                    }
                }

                if min_x <= max_x && rel_bot > rel_top {
                    let tw = max_x - min_x + 1;
                    let th = rel_bot - rel_top;
                    let mut tight = vec![0u8; tw * th];
                    for y in 0..th {
                        for x in 0..tw {
                            tight[y * tw + x] = g.mask[(rel_top + y) * orig_w + (min_x + x)];
                        }
                    }
                    (tight, tw, th)
                } else {
                    (g.mask.clone(), g.bbox.width as usize, g.bbox.height as usize)
                }
            } else {
                (g.mask.clone(), g.bbox.width as usize, g.bbox.height as usize)
            };

            // Check for critical exclamation mark: narrow, tall with gap before bottom dot
            let aspect = gw as f32 / gh as f32;
            if aspect <= 0.40 && gh >= 22 {
                let bottom_start = (gh as f32 * 0.65) as usize;
                let bottom_end = (gh as f32 * 0.85) as usize;
                let mut has_gap = false;
                for y in bottom_start..bottom_end {
                    let mut row_count = 0;
                    for x in 0..gw {
                        if crop_mask[y * gw + x] > 0 {
                            row_count += 1;
                        }
                    }
                    if row_count == 0 {
                        has_gap = true;
                        break;
                    }
                }
                if has_gap {
                    has_crit_mark = true;
                    continue; // Skip exclamation mark from numerical digits
                }
            }

            // Touching glyphs split
            if aspect >= 1.15 && gw >= 20 {
                let sub_glyphs = self.split_touching_glyphs(&crop_mask, gw, gh);
                if sub_glyphs.len() >= 2 {
                    for (crop, cw, ch) in sub_glyphs {
                        let sub_asp = cw as f32 / ch as f32;
                        if sub_asp < 0.18 || sub_asp > 0.98 {
                            continue;
                        }
                        let (digit, conf) = self.templates.match_glyph(&crop, cw, ch);
                        if conf >= 0.50 {
                            recognized_digits.push(digit);
                            total_conf += conf;
                        }
                    }
                    continue;
                }
            }

            // An unsplit single digit in Genshin never exceeds aspect 0.98
            if aspect > 0.98 {
                continue;
            }

            let (digit, conf) = self.templates.match_glyph(&crop_mask, gw, gh);
            if conf >= 0.50 {
                recognized_digits.push(digit);
                total_conf += conf;
            }
        }

        // In a real damage number, all non-crit glyphs must be recognized as digits
        let expected_digits = cluster.glyphs.len().saturating_sub(if has_crit_mark { 1 } else { 0 });
        if recognized_digits.len() < expected_digits || recognized_digits.len() < 2 {
            return None;
        }

        let avg_conf = total_conf / recognized_digits.len() as f32;
        if avg_conf < 0.62 {
            return None;
        }

        // All-ones rejection: "11", "111", "1111" etc. are the most common false positive
        // pattern from vertical environmental features (tree trunks, pillars, edges).
        // Real all-1 damage numbers are extremely rare and would have higher confidence.
        let all_ones = recognized_digits.iter().all(|&d| d == 1);
        if all_ones && avg_conf < 0.82 {
            return None;
        }

        let mut value = 0u32;
        for d in recognized_digits.iter() {
            value = value.saturating_mul(10).saturating_add(*d);
        }

        // Damage bounds: realistic range in Genshin Impact
        if value < 10 || value > 99_999_999 {
            return None;
        }

        let is_crit = has_crit_mark || cluster.bbox.height >= 27;

        Some(RecognizedHit {
            value,
            is_crit,
            confidence: avg_conf,
            x: cluster.bbox.x as i32 + (cluster.bbox.width as i32 / 2),
            y: cluster.bbox.y as i32,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_template_self_match() {
        let matcher = DigitMatcher::new();
        for digit in 0..10 {
            let t = &matcher.templates.templates[digit];
            if digit == 1 {
                let mut narrow = [0u8; 8 * 24];
                for y in 0..24 {
                    for x in 0..8 {
                        narrow[y * 8 + x] = t[y * 16 + (8 + x)];
                    }
                }
                let (matched, score) = matcher.templates.match_glyph(&narrow, 8, 24);
                assert_eq!(matched, 1, "Self match failed for digit 1");
                assert!(score >= 0.70, "Self match score {} too low for digit 1", score);
            } else {
                let (matched, score) = matcher.templates.match_glyph(t, TEMPLATE_W, TEMPLATE_H);
                assert_eq!(matched, digit as u32, "Self match failed for digit {}", digit);
                assert!(score >= 0.80, "Self match score {} too low for digit {}", score, digit);
            }
        }
    }
}
